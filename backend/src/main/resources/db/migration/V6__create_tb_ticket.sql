CREATE TABLE tb_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(30) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(30) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    type VARCHAR(30) NOT NULL,
    requester_id BIGINT NOT NULL REFERENCES tb_user (id),
    assignee_id BIGINT REFERENCES tb_user (id),
    assigned_group_id BIGINT REFERENCES tb_support_group (id),
    ticket_category_id BIGINT REFERENCES tb_ticket_category (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    first_response_at TIMESTAMP WITH TIME ZONE,
    resolved_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    due_at TIMESTAMP WITH TIME ZONE,
    resolution TEXT,
    CONSTRAINT uk_ticket_reference UNIQUE (reference)
);

CREATE INDEX idx_ticket_status ON tb_ticket (status);
CREATE INDEX idx_ticket_priority ON tb_ticket (priority);
CREATE INDEX idx_ticket_requester ON tb_ticket (requester_id);
CREATE INDEX idx_ticket_assignee ON tb_ticket (assignee_id);
CREATE INDEX idx_ticket_assigned_group ON tb_ticket (assigned_group_id);
CREATE INDEX idx_ticket_category ON tb_ticket (ticket_category_id);
